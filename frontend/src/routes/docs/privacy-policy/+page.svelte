<article class="prose prose-invert">
	<span class="bt-eyebrow not-prose text-ink-muted mb-3">Live Quiz</span>
	<h1>Privacy</h1>
	<p>
		India Tech Hub Live Quiz is operated by the event organisers. It stores only what the game
		needs.
	</p>
	<h2>Players</h2>
	<table>
		<thead>
			<tr>
				<th>What</th>
				<th>Why</th>
				<th>How long</th>
			</tr>
		</thead>
		<tbody>
			<tr>
				<td>The nickname you choose</td>
				<td>To show your score and rank during the game</td>
				<td>Kept with the game results</td>
			</tr>
			<tr>
				<td>Your answers and answer times</td>
				<td>To score the game and publish the results</td>
				<td>Kept with the game results</td>
			</tr>
		</tbody>
	</table>
	<p>
		Players do not need an account. You do not have to use your real name as a nickname. If the
		organisers add an extra field on the join screen, such as a team name, what you enter there
		is kept with the results as well.
	</p>
	<h2>Organisers</h2>
	<p>
		Organiser accounts store an email address, a username, a hashed password and the quizzes
		they create, for as long as the account exists. A session cookie keeps organisers signed in.
	</p>
	<h2>Technical data</h2>
	<p>
		The server keeps short-lived technical logs, including IP addresses, to run the service and
		prevent abuse. No advertising or third-party tracking is used.
	</p>
	<h2>Your data</h2>
	<p>To ask for your data to be corrected or deleted, speak to the event organisers.</p>

	<ul>
		<li>Choose a nickname that is respectful. Organisers can remove any nickname.</li>
		<li>Play fairly: one device per person, and no automated answers.</li>
		<li>
			Scores and the leaderboard are shown on the big screen during the event, under your
			nickname.
		</li>
	</ul>
	<h2>Organiser accounts</h2>
	<p>
		Accounts are for event organisers who create and host quizzes. Quiz content must be suitable
		for a professional audience. Organisers may edit or delete any content on the service.
	</p>
	<h2>Availability</h2>
	<p>
		The service is provided for the event as it is. It may be changed, paused or closed after
		the event.
	</p>
	<p>For any question, speak to the event organisers.</p>
